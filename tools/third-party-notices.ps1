#requires -Version 7
# PLATFORM: any (PowerShell 7 and cargo). It lists the crates of the Windows build; pass another
# -Target when the macOS and Linux ports start.
#
# Writes THIRD-PARTY-NOTICES.txt at the repository root: every third-party component that is
# built into Crucible's programs, with its licence and the licence texts found in its package.
# The MIT, BSD and Apache licences require their notices to travel with the binaries, so the
# installer ships this file (app/src-tauri/tauri.bundle.json).
#
# Run it after any dependency change, then commit the result:
#   pwsh -File tools\third-party-notices.ps1
param([string]$Target = 'x86_64-pc-windows-msvc')
$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot -Parent
$json = cargo metadata --format-version 1 --filter-platform $Target --manifest-path (Join-Path $root 'Cargo.toml')
if ($LASTEXITCODE -ne 0) { throw 'cargo metadata failed' }
$meta = $json | ConvertFrom-Json -AsHashtable

$packages = @{}; foreach ($p in $meta.packages) { $packages[$p.id] = $p }
$nodes = @{}; foreach ($n in $meta.resolve.nodes) { $nodes[$n.id] = $n }

# Everything reachable from Crucible's own crates through normal dependencies: what gets linked.
# Build-time tools (build scripts, bindgen) are not part of the programs and are left out.
$linked = [System.Collections.Generic.HashSet[string]]::new()
$todo = [System.Collections.Generic.Stack[string]]::new()
foreach ($m in $meta.workspace_members) { $todo.Push($m) }
while ($todo.Count -gt 0) {
  $id = $todo.Pop()
  if (-not $linked.Add($id)) { continue }
  foreach ($d in $nodes[$id].deps) {
    if (@($d.dep_kinds | Where-Object { $null -eq $_.kind }).Count -gt 0) { $todo.Push($d.pkg) }
  }
}
$own = [System.Collections.Generic.HashSet[string]]::new([string[]]$meta.workspace_members)
$third = $linked | Where-Object { -not $own.Contains($_) } | ForEach-Object { $packages[$_] } | Sort-Object { $_.name }, { $_.version }

function Read-Notice([string]$path) {
  ((Get-Content -LiteralPath $path -Raw -Encoding utf8) -replace "`r`n", "`n" -replace "`r", "`n" -replace "[ `t]+`n", "`n").Trim()
}

# Licence texts, each kept once however many crates carry the same one.
$texts = [ordered]@{}   # text -> list of "name version"
$bare = @()             # crates whose package has no licence file
foreach ($p in $third) {
  $dir = Split-Path $p.manifest_path -Parent
  $files = Get-ChildItem -LiteralPath $dir -File | Where-Object { $_.Name -match '^(LICEN[SC]E|COPYING|COPYRIGHT|NOTICE|UNLICENSE)' } | Sort-Object Name
  if (-not $files) { $bare += $p; continue }
  foreach ($f in $files) {
    $t = Read-Notice $f.FullName
    if (-not $t) { continue }
    if (-not $texts.Contains($t)) { $texts[$t] = [System.Collections.Generic.List[string]]::new() }
    $who = "$($p.name) $($p.version)"
    if (-not $texts[$t].Contains($who)) { $texts[$t].Add($who) }
  }
}

$rule = '=' * 78
$out = [System.Text.StringBuilder]::new()
function Say([string]$s = '') { [void]$out.Append($s).Append("`n") }

Say 'CRUCIBLE: THIRD-PARTY NOTICES'
Say $rule
Say
Say 'Crucible is free software under the GNU General Public License, version 3 or later'
Say '(LICENSE.txt beside this file). Its source code is at'
Say 'https://github.com/dzykel60687/crucible'
Say
Say 'The programs include the third-party components listed here. Each stays under its own'
Say 'licence, shown beside it; the texts follow in part 3. This file is generated by'
Say 'tools/third-party-notices.ps1 and is not edited by hand.'
Say
Say $rule
Say '1. COMPONENTS THAT ARE NOT RUST CRATES'
Say $rule
Say
Say 'Steinberg ASIO SDK 2.3.4 (host part)'
Say '  (c) 2025 Steinberg Media Technologies GmbH. Used under the GNU General Public License'
Say '  version 3, one of the two licences the SDK is offered under. Source: third-party/asiosdk'
Say '  in the Crucible repository. ASIO is a trademark and software of Steinberg Media'
Say '  Technologies GmbH.'
Say
Say 'The Rust standard library'
Say '  Copyright (c) The Rust Project Contributors. MIT OR Apache-2.0.'
Say '  https://github.com/rust-lang/rust'
Say
Say 'Inter typeface'
Say '  SIL Open Font License 1.1. Notice and licence in part 3.'
Say
Say 'JetBrains Mono typeface'
Say '  SIL Open Font License 1.1. Notice and licence in part 3.'
Say
Say '@tauri-apps/api (JavaScript)'
Say '  Copyright (c) 2017 - Present Tauri Apps Contributors. Apache-2.0 OR MIT.'
Say '  https://github.com/tauri-apps/tauri'
Say
Say $rule
Say "2. RUST CRATES ($(@($third).Count))"
Say $rule
Say
foreach ($p in $third) {
  $where = if ($p.repository) { $p.repository } else { "https://crates.io/crates/$($p.name)" }
  Say "$($p.name) $($p.version)  |  $($p.license)  |  $where"
}
if ($bare) {
  Say
  Say 'These crates ship no licence file in their package. Their licence is the one declared'
  Say 'above, and the standard texts of those licences are in part 3:'
  Say ('  ' + (($bare | ForEach-Object { "$($_.name) $($_.version)" }) -join ', '))
}
Say
Say $rule
Say '3. LICENCE TEXTS'
Say $rule

function Say-Text([string]$title, [string]$text) {
  Say
  Say ('-' * 78)
  Say $title
  Say ('-' * 78)
  Say
  Say $text
}
foreach ($f in 'Inter-OFL.txt', 'JetBrainsMono-OFL.txt') {
  Say-Text "Typeface: $($f -replace '-OFL.txt', '')" (Read-Notice (Join-Path $root "app/src/fonts/$f"))
}
$api = Join-Path $root 'app/node_modules/@tauri-apps/api'
foreach ($f in 'LICENSE-MIT', 'LICENSE-APACHE-2.0') {
  $path = Join-Path $api $f
  if (-not (Test-Path $path)) { throw "missing ${path}: run npm install in app/ first" }
  $t = Read-Notice $path
  if (-not $texts.Contains($t)) { $texts[$t] = [System.Collections.Generic.List[string]]::new() }
  $texts[$t].Add('@tauri-apps/api')
}
# Longest lists first: the shared Apache-2.0 and MIT texts lead, one-crate notices follow.
foreach ($e in ($texts.GetEnumerator() | Sort-Object { -$_.Value.Count }, { $_.Value[0] })) {
  Say-Text ("Used by: " + ($e.Value -join ', ')) $e.Key
}

$file = Join-Path $root 'THIRD-PARTY-NOTICES.txt'
[System.IO.File]::WriteAllText($file, $out.ToString(), [System.Text.UTF8Encoding]::new($false))
"{0}: {1} crates, {2} without a licence file, {3} distinct texts, {4:N0} bytes" -f (Split-Path $file -Leaf), @($third).Count, @($bare).Count, $texts.Count, (Get-Item $file).Length
